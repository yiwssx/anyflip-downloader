#!/usr/bin/env bash
# RCAT AnyFlip: recover ONLY an operator-pinned Svelte image after quota mount.
# Never builds, pulls, changes credentials, removes volumes or edits host Compose.
set -Eeuo pipefail

die() { printf 'SVELTE_BOOT=BLOCKED reason=%s\n' "$*" >&2; exit 1; }
[[ "${EUID}" -eq 0 ]] || die "root-required"
[[ "$#" -eq 1 && ( "$1" == check || "$1" == ensure ) ]] ||
  die "usage: $0 check|ensure"
action="$1"
state="/etc/rcat-anyflip-svelte"
[[ -f "$state/active.env" && -f "$state/compose.pinned.yaml" ]] ||
  die "approved-release-metadata-missing"
for cmd in docker python3 systemctl curl; do
  command -v "$cmd" >/dev/null 2>&1 || die "missing-$cmd"
done
docker compose version >/dev/null 2>&1 || die "compose-v2-required"

# Root-owned state file is generated by install-svelte-boot.sh, no secrets.
# shellcheck disable=SC1091
source "$state/active.env"
[[ "${BOOT_HOST:-}" == "/opt/anyflip-downloader" ]] || die "unexpected-host-path"
[[ "${BOOT_PROJECT:-}" =~ ^[a-zA-Z0-9][a-zA-Z0-9_.-]*$ ]] || die "invalid-project"
[[ "${BOOT_IMAGE_ID:-}" =~ ^sha256:[a-f0-9]{64}$ ]] || die "invalid-image-id"
[[ "${BOOT_SOURCE_SHA:-}" =~ ^[a-f0-9]{40}$ ]] || die "invalid-source-revision"
[[ "${BOOT_IMAGE_TAG:-}" =~ ^rcat-anyflip-svelte:boot-[a-f0-9]{12}-[a-f0-9]{12}$ ]] ||
  die "invalid-pinned-image-tag"
case "${BOOT_PORT:-}" in
  10.10.1.100:8094|127.0.0.1:8094) ;;
  *) die "unexpected-LAN-binding" ;;
esac
[[ -n "${BOOT_MOUNTS:-}" && "$BOOT_MOUNTS" == *"/data/jobs"* ]] ||
  die "quota-mount-evidence-missing"
[[ -f "$BOOT_HOST/.env" && -f "$BOOT_HOST/compose.web.yaml" &&
   -f "$BOOT_HOST/compose.quota.yaml" ]] ||
  die "host-compose-env-or-quota-file-missing"
systemctl is-active --quiet anyflip-quota.service ||
  die "hard-quota-service-inactive"
docker image inspect "$BOOT_IMAGE_TAG" >/dev/null 2>&1 || die "pinned-image-not-found"
actual_image="$(docker image inspect --format '{{.Id}}' "$BOOT_IMAGE_TAG")"
[[ "$actual_image" == "$BOOT_IMAGE_ID" ]] || die "pinned-image-was-replaced"
actual_revision="$(docker image inspect --format '{{index .Config.Labels "org.opencontainers.image.revision"}}' "$BOOT_IMAGE_TAG")"
[[ "$actual_revision" == "$BOOT_SOURCE_SHA" ]] || die "pinned-source-mismatch"

export RCAT_SVELTE_IMAGE="$BOOT_IMAGE_TAG"
compose=(docker compose --project-directory "$BOOT_HOST" -p "$BOOT_PROJECT"
  --env-file "$BOOT_HOST/.env"
  -f "$BOOT_HOST/compose.web.yaml"
  -f "$BOOT_HOST/compose.quota.yaml"
  -f "$state/compose.pinned.yaml")
# Do not print resolved Compose config: it contains OAuth client secrets.
"${compose[@]}" config --format json | python3 -c '
import json,sys
image=sys.argv[1]; port=sys.argv[2]
service=json.load(sys.stdin)["services"]["anyflip-web"]
assert service["image"]==image, "boot image not pinned"
assert service["environment"].get("ANYFLIP_WEB_UI")=="svelte", "frontend mode not Svelte"
assert service["environment"].get("ANYFLIP_AUTH_MODE")=="google", "Google auth missing"
assert not service.get("build"), "boot must not build/rebuild images"
ports=service.get("ports",[])
assert any(str(p.get("published"))=="8094" and
           str(p.get("host_ip", ""))==port.rsplit(":",1)[0] and
           int(p.get("target"))==8080 for p in ports), "port mismatch"
assert service.get("volumes"), "quota job volume missing"
' "$BOOT_IMAGE_TAG" "$BOOT_PORT" || die "composed-config-is-not-approved"

mapfile -t ids < <(docker ps -aq
  --filter "label=com.docker.compose.project=$BOOT_PROJECT"
  --filter "label=com.docker.compose.service=anyflip-web")
[[ "${#ids[@]}" -eq 1 ]] || die "expected-one-existing-container"
cid="${ids[0]}"
actual_service="$(docker inspect --format '{{index .Config.Labels "com.docker.compose.service"}}' "$cid")"
[[ "$actual_service" == anyflip-web ]] || die "unexpected-service"
mounts="$(docker inspect --format '{{range .Mounts}}{{.Type}}|{{.Name}}|{{.Source}}|{{.Destination}};{{end}}' "$cid")"
[[ "$mounts" == "$BOOT_MOUNTS" ]] || die "job-volume-or-mount-changed"
port="$(docker inspect --format '{{range (index .HostConfig.PortBindings "8080/tcp")}}{{.HostIp}}:{{.HostPort}}{{end}}' "$cid")"
[[ "$port" == "$BOOT_PORT" ]] || die "LAN-port-changed"
old_id="$(docker inspect --format '{{.Image}}' "$cid")"
old_mode="$(docker inspect --format '{{range .Config.Env}}{{if eq . "ANYFLIP_WEB_UI=svelte"}}svelte{{end}}{{end}}' "$cid")"
old_auth="$(docker inspect --format '{{range .Config.Env}}{{if eq . "ANYFLIP_AUTH_MODE=google"}}google{{end}}{{end}}' "$cid")"
[[ "$old_auth" == google ]] || die "existing-google-auth-missing"

verify() {
  local target="$1" healthy=0 status c
  for _ in {1..30}; do
    c="$(docker inspect --format '{{if .State.Running}}{{if .State.Health}}{{.State.Health.Status}}{{else}}unknown{{end}}{{else}}stopped{{end}}' "$target")"
    if [[ "$c" == healthy ]]; then healthy=1; break; fi
    sleep 2
  done
  [[ "$healthy" == 1 ]] || return 1
  BASE_URL="http://$BOOT_PORT" CANONICAL_HOST="anyflip.rcat.ac.th" \
    sh /usr/local/libexec/rcat-anyflip-verify-svelte.sh
}
running="$(docker inspect --format '{{.State.Running}}' "$cid")"
if [[ "$old_id" == "$BOOT_IMAGE_ID" && "$old_mode" == svelte && "$running" == true ]]; then
  # The common reboot path is NO-OP: never recreate a healthy matching service.
  if verify "$cid"; then
    echo "SVELTE_BOOT=PASS"
    echo "SVELTE_BOOT_ACTION=NOOP"
    exit 0
  fi
  [[ "$action" == ensure ]] || die "pinned-image-unhealthy-no-mutation"
fi
if [[ "$action" == check ]]; then
  echo "SVELTE_BOOT=DRIFT_DETECTED"
  echo "SVELTE_BOOT_ACTION=NONE"
  exit 1
fi

# During boot we may need to replace the container recreated by the old
# quota-aware startup. Do not touch its named volume, ports, proxy or secrets.
old_restart="$(docker inspect --format '{{.HostConfig.RestartPolicy.Name}}' "$cid")"
old_mode="legacy"
if docker inspect --format '{{range .Config.Env}}{{if eq . "ANYFLIP_WEB_UI=svelte"}}yes{{end}}{{end}}' "$cid" | grep -q yes; then
  old_mode=svelte
fi
rollback_tag="rcat-anyflip-boot-previous:${old_id#sha256:}"
docker image tag "$old_id" "$rollback_tag" || die "old-image-backup-failed"
tmp="$(mktemp -d /run/anyflip-svelte-boot.XXXXXX)"
chmod 700 "$tmp"
cat > "$tmp/rollback.yaml" <<EOF
services:
  anyflip-web:
    image: "$rollback_tag"
    build: null
    restart: "$old_restart"
    environment:
      ANYFLIP_WEB_UI: "$old_mode"
EOF
# Use the existing base+quota, never the Svelte pinned overlay for rollback.
old_compose=(docker compose --project-directory "$BOOT_HOST" -p "$BOOT_PROJECT"
  --env-file "$BOOT_HOST/.env"
  -f "$BOOT_HOST/compose.web.yaml"
  -f "$BOOT_HOST/compose.quota.yaml"
  -f "$tmp/rollback.yaml")
changed=0
accepted=0
on_exit() {
  local code=$?
  if [[ "$code" -ne 0 && "$changed" == 1 && "$accepted" != 1 ]]; then
    echo "SVELTE_BOOT_RECOVERY=FAILED_ROLLING_BACK" >&2
    "${old_compose[@]}" up -d --no-build --no-deps --force-recreate anyflip-web ||
      echo "SVELTE_BOOT_ROLLBACK=FAILED_HOST_ACTION_REQUIRED" >&2
  fi
  rm -rf -- "$tmp"
}
trap on_exit EXIT

changed=1
"${compose[@]}" up -d --no-build --no-deps --force-recreate anyflip-web
new_id="$("${compose[@]}" ps -q anyflip-web)"
[[ -n "$new_id" ]] || die "recreated-container-missing"
[[ "$(docker inspect --format '{{.Image}}' "$new_id")" == "$BOOT_IMAGE_ID" ]] ||
  die "incorrect-runtime-image-after-boot"
[[ "$(docker inspect --format '{{range .Config.Env}}{{if eq . "ANYFLIP_WEB_UI=svelte"}}yes{{end}}{{end}}' "$new_id")" == yes ]] ||
  die "legacy-mode-after-boot"
[[ "$(docker inspect --format '{{range .Mounts}}{{.Type}}|{{.Name}}|{{.Source}}|{{.Destination}};{{end}}' "$new_id")" == "$BOOT_MOUNTS" ]] ||
  die "quota-mount-changed-after-boot"
[[ "$(docker inspect --format '{{range (index .HostConfig.PortBindings "8080/tcp")}}{{.HostIp}}:{{.HostPort}}{{end}}' "$new_id")" == "$BOOT_PORT" ]] ||
  die "bind-changed-after-boot"
verify "$new_id" || die "post-recovery-svelte-smoke-failed"
accepted=1
echo "SVELTE_BOOT=PASS"
echo "SVELTE_BOOT_ACTION=RECOVERED_PINNED_SVELTE"
